#!/usr/bin/env bash
# Combines the migrations and seed data into supabase/setup.sql: one file to paste into the Supabase SQL editor.
set -euo pipefail
cd "$(dirname "$0")/.."
{
  echo "-- Caemora Inventory: complete database setup. Generated by scripts/build-setup-sql.sh; do not edit by hand."
  echo "-- Paste into Supabase → SQL Editor → New query, and Run. Safe only on a new, empty project."
  echo
  for f in supabase/migrations/*.sql supabase/seed.sql; do echo "-- ===== $f"; cat "$f"; echo; done
} > supabase/setup.sql
echo "Wrote supabase/setup.sql ($(wc -l < supabase/setup.sql) lines)"
